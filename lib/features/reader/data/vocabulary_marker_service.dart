  final Set<String> _cet6 = {};
  final Set<String> _ielts = {};
  final Set<String> _toefl = {};
  bool _loaded = false;

  Future<void> ensureLoaded() async {
    if (_loaded) return;
    _cet6.addAll(_sampleCet6);
    _ielts.addAll(_sampleIelts);
    _toefl.addAll(_sampleToefl);
    _loaded = true;
  }

  Set<String> get cet6 => _cet6;
  Set<String> get ielts => _ielts;
  Set<String> get toefl => _toefl;

  bool isVocabularyWord(String word) {
    final lower = word.toLowerCase();
    return _cet6.contains(lower) || _ielts.contains(lower) || _toefl.contains(lower);
  }

  /// 扫描文本，返回所有生词的位置 [(word, start, end)]
  List<(String, int, int)> scanText(String text) {
    final result = <(String, int, int)>[];
    final wordRegex = RegExp(r"[a-zA-Z]+(?:'[a-zA-Z]+)?");
    for (final match in wordRegex.allMatches(text)) {
      if (isVocabularyWord(match.group(0)!)) {
        result.add((match.group(0)!, match.start, match.end));
      }
    }
    return result;
  }

